// Helper to deduplicate stations while ensuring shared lines are retained
const stationMapInternal = new Map<string, Station>();

[
  ...KRL_CIKARANG_STATIONS,
  ...KRL_BOGOR_STATIONS,
  ...KRL_RANGKASBITUNG_STATIONS,
  ...KRL_TANGERANG_STATIONS,
  ...KRL_SENEN_STATIONS,
  ...TJ_CORRIDOR_1_STATIONS,
  ...MRT_NS_STATIONS,
  ...LRT_JAKARTA_STATIONS,
  ...LRT_JABODEBEK_CIBUBUR_STATIONS,
  ...LRT_JABODEBEK_BEKASI_STATIONS,
  ...KAI_BANDARA_STATIONS,
].forEach((station) => {
  const existing = stationMapInternal.get(station.id);
  if (existing) {
    const mergedLines = Array.from(new Set([...existing.lines, ...station.lines]));
    stationMapInternal.set(station.id, {
      ...existing,
      lines: mergedLines,
      isInterchange: mergedLines.length > 1 || existing.isInterchange || station.isInterchange,
    });
  } else {
    stationMapInternal.set(station.id, station);
  }
});

export const STATIONS: Station[] = Array.from(stationMapInternal.values());

export const STATION_MAP: Record<string, Station> = STATIONS.reduce((acc, station) => {
  acc[station.id] = station;
  return acc;
}, {} as Record<string, Station>);

