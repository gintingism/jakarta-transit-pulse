import { TRANSIT_TRACK_GEOMETRIES } from './transitGeometries';
export type TransitType = 'krl' | 'tj' | 'mrt' | 'lrt';
export type LineIdentifier =
  | 'krl-cikarang'
  | 'krl-cikarang-senen'
  | 'krl-bogor'
  | 'krl-rangkasbitung'
  | 'krl-tangerang'
  | 'tj-corridor-1'
  | 'mrt-ns'
  | 'lrt-jakarta'
  | 'lrt-cibubur'
  | 'lrt-bekasi'
  | 'kai-bandara';

export interface Station {
  id: string;
  name: string;
  code?: string;
  type: TransitType;
  lines: LineIdentifier[];
  coords: [number, number]; // [lat, lng]
  coordinates: [number, number]; // [lat, lng] alias for map interop
  isInterchange: boolean;
  interchangeWith?: string[]; // Connected physical station IDs
  description?: string;
  passThroughOnly?: boolean;
}

export interface TransitLine {
  id: LineIdentifier;
  name: string;
  shortName: string;
  type: TransitType;
  color: string;
  textColor: string;
  direction: string;
  headwayMinutes: number;
  stations: string[]; // Ordered station IDs
  trackCoords?: [number, number][];
}

export interface InterchangeNode {
  fromStationId: string;
  toStationId: string;
  walkMinutes: number;
  description: string;
}

export type InterchangeConnection = InterchangeNode;

